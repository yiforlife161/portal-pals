const {chromium}=require('playwright');const fs=require('fs');const path=require('path');
const db=require('./server.js');
const OLD=process.argv[2], NEW=process.argv[3]||'../index.html';
let html=fs.readFileSync(path.join(__dirname,OLD),'utf8');
(async()=>{const b=await chromium.launch();const ctx=await b.newContext({viewport:{width:1000,height:700}});
await ctx.route(/fonts\.g/,r=>r.abort());
await ctx.route('https://pp.test/**',r=>r.fulfill({body:html,contentType:'text/html'}));
await ctx.route('https://www.gstatic.com/**',r=>{const f=r.request().url().split('/').pop().replace('firebase-','').replace('firestore','fs');return r.fulfill({body:fs.readFileSync(path.join(__dirname,f),'utf8'),contentType:'application/javascript'});});
await ctx.exposeFunction('__db',(op,u,a)=>db(op,u,a));
await ctx.addInitScript(()=>{localStorage.setItem('mock.want',JSON.stringify({uid:'uidA',displayName:'Ana'}));});
const pg=await ctx.newPage();pg.on('pageerror',e=>console.log('ERR',e.message));
pg.on('console',m=>{if(/LOADFAIL|warn/.test(m.text()+m.type()))console.log('C',m.text().slice(0,300))});
pg.on('framenavigated',f=>{if(f===pg.mainFrame())console.log('  [navigated]')});
const hud=()=>pg.evaluate(()=>(window.__st&&window.__st.island?('STATE gold '+window.__st.island.gold+' tut '+window.__st.island.tut+' items '+window.__st.island.items.length+' | '):'nostate | ')+(document.querySelector('.hud')?document.querySelector('.hud').innerText.replace(/\n/g,' '):'-'));
const st=()=>pg.evaluate(()=>{const o=JSON.parse(localStorage.getItem(window.PP_SAVE_KEY)||'null');return o&&[o.island.gold,o.t]});
await pg.goto('https://pp.test/');await pg.waitForTimeout(1200);
await pg.click('#pp-signin');await pg.waitForTimeout(4000);
await pg.evaluate(()=>{const k=window.PP_SAVE_KEY;const o=JSON.parse(localStorage.getItem(k));o.island.gold=54321;o.island.tut=99;o.t=Date.now();localStorage.setItem(k,JSON.stringify(o));window.ppNoSave=true;});
console.log('--- reload old');await pg.reload();await pg.waitForTimeout(4000);
console.log('old hud',await hud(),await st(),'cloud',(db.DB['saves/uidA']||{}).t);
html=fs.readFileSync(path.join(__dirname,NEW),'utf8');
console.log('--- reload new');await pg.reload();await pg.waitForTimeout(5000);
console.log('new hud',await hud(),await st(),'cloud',(db.DB['saves/uidA']||{}).t);
await pg.waitForTimeout(15000);
console.log('later hud',await hud(),await st(),'cloud',(db.DB['saves/uidA']||{}).t);
await b.close();})();
